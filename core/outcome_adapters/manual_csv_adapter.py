# 3. CANONICAL NUMERIC PARSING (SECTION 5)
# -------------------------------------------------------------
FORBIDDEN_CURRENCY_SYMBOLS = {"₹", "$", "€", "£", "¥"}

def parse_canonical_numeric_string(val: Any, field_name: str) -> Optional[str]:
    """
    Validates canonical CSV numeric representation.
    Rejects currency symbols, ambiguous thousands separators (e.g. ₹1,23,456 or 1,234.50).
    Returns cleaned string or None if empty.
    """
    if val is None:
        return None
    val_str = str(val).strip()
    if val_str == "":
        return None

    # Check for currency symbols
    for sym in FORBIDDEN_CURRENCY_SYMBOLS:
        if sym in val_str:
            raise ValueError(
                f"{ERROR_INVALID_NUMERIC_VALUE}: Field '{field_name}' contains currency symbol '{sym}' ('{val_str}'). "
                "Use canonical decimal numeric representation (e.g. 125000.50)."
            )

    # Check for thousands commas
    if "," in val_str:
        raise ValueError(
            f"{ERROR_INVALID_NUMERIC_VALUE}: Field '{field_name}' contains thousands comma separator ('{val_str}'). "
            "Use canonical unpunctuated numeric representation (e.g. 125000.50)."
        )

    return val_str


