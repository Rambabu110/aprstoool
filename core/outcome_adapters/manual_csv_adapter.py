# 4. MANUAL CSV OUTCOME ADAPTER CLASS
# -------------------------------------------------------------
class ManualCsvOutcomeAdapter(OutcomeSourceAdapter):
    """
    Production adapter for local CSV outcome files.
    Implements OutcomeSourceAdapter contract without external APIs or direct DB writes.
    """

    def __init__(self, version: str = CSV_SOURCE_VERSION):
        self._version = version

    @property
    def source_name(self) -> str:
        return SOURCE_MANUAL_CSV

    @property
    def source_version(self) -> str:
        return self._version

    @property
    def source_schema_version(self) -> str:
        return CSV_SCHEMA_VERSION

    def validate_source_record(self, record: Dict[str, Any]) -> ValidationResult:
        """
        Validates individual CSV row dictionary structure without throwing unhandled exceptions.
        """
        result = ValidationResult(is_valid=True)
        if not isinstance(record, dict):
            result.add_error("Source record must be a dictionary.", ERROR_INVALID_SOURCE_RECORD)
            return result

        # 1. Check research proxy boundary
        data_src = record.get("data_source", self.source_name)
        try:
            check_research_proxy_rejection(data_src, record)
        except ValueError as e:
            result.add_error(str(e), ERROR_RESEARCH_ESTIMATE_NOT_OUTCOME)
            return result

        # 2. Check product identity presence
        raw_pid = record.get("product_id") or record.get("aprs_product_id")
        src_pid = record.get("source_product_id") or record.get("sku") or record.get("asin")
        if not raw_pid and not src_pid:
            result.add_error("Row must contain 'product_id' or 'source_product_id'.", ERROR_MISSING_PRODUCT_ID)

        # 3. Check source_record_id presence (Required for CSV)
        src_rec_id = record.get("source_record_id")
        if not src_rec_id or str(src_rec_id).strip() == "":
            result.add_error("Row must contain non-empty 'source_record_id'.", ERROR_INVALID_SOURCE_RECORD)

        # 4. Check period validity
        p_start = record.get("period_start")
        p_end = record.get("period_end")
        p_type = record.get("period_type", "DAY_30")
        try:
            validate_and_normalize_period(p_start, p_end, p_type)
        except ValueError as e:
            err_str = str(e)
            cat = ERROR_UNSUPPORTED_PERIOD_TYPE if ERROR_UNSUPPORTED_PERIOD_TYPE in err_str else ERROR_INVALID_PERIOD
            result.add_error(err_str, cat)

        # 5. Check numeric formats
        for field_name in (
            "units_sold", "actual_units_sold", "units", "revenue", "actual_revenue", "gross_sales",
            "landed_cogs", "actual_landed_cogs", "cogs", "returns_count", "actual_returns_count", "returns",
            "rto_count", "actual_rto_count", "rto", "ad_spend", "actual_ad_spend", "marketing_spend",
            "inventory", "actual_inventory", "stockout_days", "actual_stockout_days",
            "avg_selling_price", "actual_avg_selling_price", "asp", "selling_price",
            "contribution_margin", "actual_contribution_margin", "cm", "cm_pct", "actual_cm_pct",
            "return_rate_pct", "actual_return_rate_pct", "rto_rate_pct", "actual_rto_rate_pct",
            "cac", "actual_cac"
        ):
            if field_name in record and record[field_name] is not None and str(record[field_name]).strip() != "":
                try:
                    clean_str = parse_canonical_numeric_string(record[field_name], field_name)
                    if "rate" in field_name or "pct" in field_name:
                        clean_percentage(clean_str, field_name)
                    elif any(k in field_name for k in ("units", "count", "inventory", "days")):
                        clean_non_negative_int(clean_str, field_name)
                    else:
                        clean_non_negative_float(clean_str, field_name)
                except ValueError as e:
                    err_str = str(e)
                    cat = ERROR_INVALID_PERCENTAGE if "PERCENTAGE" in err_str else ERROR_INVALID_NUMERIC_VALUE
                    result.add_error(err_str, cat)

        # 6. Check for conflicting metric aliases (CHECK #3)
        alias_errs = check_metric_alias_conflicts(record)
        for a_err in alias_errs:
            result.add_error(a_err, ERROR_INVALID_NUMERIC_VALUE)

        return result

    def normalize(
        self,
        record: Dict[str, Any],
        product_resolver: Optional[Callable[[str], Optional[str]]] = None
    ) -> NormalizedOutcome:
        """
        Normalizes a parsed CSV row into canonical NormalizedOutcome.
        Preserves NULL semantics (blank numeric fields remain None; explicit 0 remains 0).
        """
        if not isinstance(record, dict):
            raise ValueError(f"{ERROR_INVALID_SOURCE_RECORD}: Row record must be a dictionary.")

        # 1. Enforce research proxy boundary
        data_src = record.get("data_source", self.source_name)
        check_research_proxy_rejection(data_src, record)

        # 2. Check source_record_id (Strictly required for CSV)
        src_rec_id = record.get("source_record_id")
        if not src_rec_id or str(src_rec_id).strip() == "":
            raise ValueError(f"{ERROR_INVALID_SOURCE_RECORD}: Missing required 'source_record_id' in CSV row.")
        clean_source_record_id = str(src_rec_id).strip()

        # 2B. Enforce no conflicting metric aliases (CHECK #3)
        alias_errs = check_metric_alias_conflicts(record)
        if alias_errs:
            raise ValueError(alias_errs[0])

        # 3. Resolve Product Identity
        raw_pid = record.get("product_id") or record.get("aprs_product_id")
        src_pid = record.get("source_product_id") or record.get("sku") or record.get("asin")
        if raw_pid and src_pid and product_resolver is not None:
            resolved_from_src = product_resolver(str(src_pid).strip())
            if resolved_from_src and str(resolved_from_src).strip() != str(raw_pid).strip():
                raise ValueError(
                    f"{ERROR_UNRESOLVED_PRODUCT}: Conflicting product identity: product_id '{raw_pid}' "
                    f"does not match resolved source_product_id '{resolved_from_src}'."
                )

        resolved_pid = resolve_product_identity(
            raw_product_id=str(raw_pid).strip() if raw_pid else None,
            source_product_id=str(src_pid).strip() if src_pid else None,
            product_resolver=product_resolver
        )

        # 4. Validate & Normalize Calendar Period
        p_start = record.get("period_start")
        p_end = record.get("period_end")
        p_type = record.get("period_type", "DAY_30")
        clean_start, clean_end, clean_type = validate_and_normalize_period(p_start, p_end, p_type)

        # 5. Extract and preserve Decision Identity if present
        raw_dec_id = record.get("decision_id")
        clean_dec_id = None
        if raw_dec_id is not None and str(raw_dec_id).strip() != "":
            try:
                clean_dec_id = int(str(raw_dec_id).strip())
            except (ValueError, TypeError):
                raise ValueError(f"{ERROR_INVALID_NUMERIC_VALUE}: decision_id must be an integer, got '{raw_dec_id}'.")

        # 6. Extract Metrics with strict NULL preservation (None != 0)
        def _get_int(*field_keys: str) -> Optional[int]:
            for key in field_keys:
                if key in record and record[key] is not None:
                    raw_val = parse_canonical_numeric_string(record[key], key)
                    if raw_val is not None:
                        return clean_non_negative_int(raw_val, key)
            return None

        def _get_float(*field_keys: str) -> Optional[float]:
            for key in field_keys:
                if key in record and record[key] is not None:
                    raw_val = parse_canonical_numeric_string(record[key], key)
                    if raw_val is not None:
                        return clean_non_negative_float(raw_val, key)
            return None

        def _get_pct(*field_keys: str) -> Optional[float]:
            for key in field_keys:
                if key in record and record[key] is not None:
                    raw_val = parse_canonical_numeric_string(record[key], key)
                    if raw_val is not None:
                        return clean_percentage(raw_val, key)
            return None

        units = _get_int("actual_units_sold", "units_sold", "units")
        revenue = _get_float("actual_revenue", "revenue", "gross_sales")
        asp = _get_float("actual_avg_selling_price", "avg_selling_price", "asp", "selling_price")
        cogs = _get_float("actual_landed_cogs", "landed_cogs", "cogs")
        cm = _get_float("actual_contribution_margin", "contribution_margin", "cm")
        cm_pct = _get_float("actual_cm_pct", "cm_pct")
        returns = _get_int("actual_returns_count", "returns_count", "returns")
        return_rate_pct = _get_pct("actual_return_rate_pct", "return_rate_pct")
        rto = _get_int("actual_rto_count", "rto_count", "rto")
        rto_rate_pct = _get_pct("actual_rto_rate_pct", "rto_rate_pct")
        ad_spend = _get_float("actual_ad_spend", "ad_spend", "marketing_spend")
        cac = _get_float("actual_cac", "cac")
        inventory = _get_int("actual_inventory", "inventory")
        stockouts = _get_int("actual_stockout_days", "stockout_days")

        # Logical cross-checks at adapter boundary
        if returns is not None and units is not None and returns > units:
            raise ValueError(f"{ERROR_INVALID_NUMERIC_VALUE}: returns_count ({returns}) cannot exceed units_sold ({units}).")
        if rto is not None and units is not None and rto > units:
            raise ValueError(f"{ERROR_INVALID_NUMERIC_VALUE}: rto_count ({rto}) cannot exceed units_sold ({units}).")

        # 7. Extract Provenance
        src_timestamp = record.get("source_timestamp")
        raw_ref = record.get("raw_reference")
        notes = record.get("notes")

        return NormalizedOutcome(
            product_id=resolved_pid,
            source_product_id=str(src_pid).strip() if src_pid is not None else None,
            decision_id=clean_dec_id,
            period_start=clean_start,
            period_end=clean_end,
            period_type=clean_type,
            data_source=str(data_src or self.source_name),
            source_schema_version=self.source_schema_version,
            source_record_id=clean_source_record_id,
            source_timestamp=str(src_timestamp).strip() if src_timestamp is not None else None,
            raw_reference=str(raw_ref).strip() if raw_ref is not None else None,
            actual_units_sold=units,
            actual_revenue=revenue,
            actual_avg_selling_price=asp,
            actual_landed_cogs=cogs,
            actual_contribution_margin=cm,
            actual_cm_pct=cm_pct,
            actual_returns_count=returns,
            actual_return_rate_pct=return_rate_pct,
            actual_rto_count=rto,
            actual_rto_rate_pct=rto_rate_pct,
            actual_ad_spend=ad_spend,
            actual_cac=cac,
            actual_inventory=inventory,
            actual_stockout_days=stockouts,
            notes=str(notes).strip() if notes is not None else None,
        )


