# 5. CONTROLLED MANUAL CSV OUTCOME SERVICE (SECTION 12)
# -------------------------------------------------------------
class ManualCsvOutcomeService:
    """
    Coordinating service for validating, previewing, and ingesting manual CSV outcome files.
    
    Guarantees:
      - Default dry_run=True (zero production writes without explicit confirmation).
      - Default atomic=True (validation errors block entire batch from writing).
      - Idempotent deduplication (repeated ingestion does not duplicate outcomes).
      - Conflict protection (conflicting outcomes require explicit Phase 3 correction).
      - Strict file safety (rejects remote URLs; supports UTF-8 and UTF-8 BOM).
    """

    def __init__(self, adapter: Optional[ManualCsvOutcomeAdapter] = None):
        self.adapter = adapter or ManualCsvOutcomeAdapter()

    @staticmethod
    def _verify_file_safety(file_path: Union[str, Path]) -> Tuple[Path, str]:
        """
        Verifies local file path safety, reads bytes, and computes SHA-256 hash.
        Rejects remote URLs (http://, https://, ftp://).
        """
        path_str = str(file_path).strip()
        lower_path = path_str.lower()
        if lower_path.startswith(("http://", "https://", "ftp://", "file://")):
            raise ValueError(
                f"{ERROR_FILE_SAFETY_VIOLATION}: Remote or URI schemes are strictly prohibited ('{file_path}'). "
                "Only local filesystem paths are allowed."
            )

        p = Path(path_str)
        if not p.exists():
            raise FileNotFoundError(f"{ERROR_FILE_SAFETY_VIOLATION}: File not found: '{file_path}'")
        if not p.is_file():
            raise ValueError(f"{ERROR_FILE_SAFETY_VIOLATION}: Path is not a regular file: '{file_path}'")

        try:
            file_bytes = p.read_bytes()
        except Exception as e:
            raise IOError(f"{ERROR_FILE_SAFETY_VIOLATION}: Could not read file '{file_path}': {e}")

        file_hash = hashlib.sha256(file_bytes).hexdigest()
        return p, file_hash

    @staticmethod
    def _parse_csv_file(path: Path) -> Tuple[List[str], List[Dict[str, Any]]]:
        """
        Parses CSV supporting UTF-8 and UTF-8 BOM.
        Validates headers (no duplicates, required columns present).
        """
        try:
            with open(path, mode="r", encoding="utf-8-sig", newline="") as f:
                reader = csv.reader(f)
                header_row = next(reader, None)
                if not header_row:
                    raise ValueError(f"{ERROR_INVALID_SOURCE_RECORD}: CSV file is empty.")

                # Clean headers
                headers = [h.strip() for h in header_row]

                # Check duplicate headers
                if len(headers) != len(set(headers)):
                    seen = set()
                    dups = [h for h in headers if h in seen or seen.add(h)]
                    raise ValueError(
                        f"{ERROR_DUPLICATE_HEADERS}: Duplicate header column names detected in CSV: {dups}"
                    )

                # Check required headers
                header_set = set(headers)
                has_product_id = any(p in header_set for p in REQUIRED_PRODUCT_ID_HEADERS)
                if not has_product_id:
                    raise ValueError(
                        f"{ERROR_MISSING_REQUIRED_HEADERS}: Missing product identifier header. "
                        f"CSV must contain at least one of: {sorted(list(REQUIRED_PRODUCT_ID_HEADERS))}"
                    )

                missing_req = [req for req in REQUIRED_BASE_HEADERS if req not in header_set]
                if missing_req:
                    raise ValueError(
                        f"{ERROR_MISSING_REQUIRED_HEADERS}: Missing required header(s): {sorted(missing_req)}"
                    )

                rows: List[Dict[str, Any]] = []
                for row in reader:
                    # Skip completely empty rows
                    if not row or all(str(cell).strip() == "" for cell in row):
                        continue
                    row_dict = {}
                    for idx, h in enumerate(headers):
                        val = row[idx] if idx < len(row) else None
                        row_dict[h] = val
                    rows.append(row_dict)

                return headers, rows
        except (ValueError, FileNotFoundError):
            raise
        except Exception as e:
            raise ValueError(f"{ERROR_INVALID_SOURCE_RECORD}: Failed to parse CSV file: {e}")

    def validate_file(
        self,
        file_path: Union[str, Path],
        product_resolver: Optional[Callable[[str], Optional[str]]] = None,
        conn=None,
    ) -> CsvValidationReport:
        """
        Validates an entire CSV file without writing any database records.
        Detects header issues, row validation errors, duplicate source IDs, and existing conflicts.
        """
        try:
            path, file_hash = self._verify_file_safety(file_path)
            headers, raw_rows = self._parse_csv_file(path)
        except Exception as e:
            err_msg = str(e)
            cat = ERROR_FILE_SAFETY_VIOLATION
            for candidate in (ERROR_DUPLICATE_HEADERS, ERROR_MISSING_REQUIRED_HEADERS, ERROR_INVALID_SOURCE_RECORD):
                if candidate in err_msg:
                    cat = candidate
                    break
            return CsvValidationReport(
                is_valid=False,
                file_path=str(file_path),
                file_hash="",
                errors=[CsvRowError(row_number=0, source_record_id=None, error_category=cat, error_message=err_msg)]
            )

        # Track ignored extra columns
        ignored_cols = [c for c in headers if c not in KNOWN_CSV_COLUMNS]

        report = CsvValidationReport(
            is_valid=True,
            file_path=str(path),
            file_hash=file_hash,
            total_rows=len(raw_rows),
            ignored_columns=ignored_cols,
        )

        seen_source_ids: Set[str] = set()
        db_conn = conn
        close_conn = False

        if db_conn is None:
            try:
                db_conn = get_connection()
                close_conn = True
            except Exception:
                db_conn = None

        try:
            for idx, row in enumerate(raw_rows, start=1):
                src_rec_id = row.get("source_record_id")
                clean_src_id = str(src_rec_id).strip() if src_rec_id is not None else None

                # Check duplicate source_record_id within the file
                if clean_src_id:
                    if clean_src_id in seen_source_ids:
                        report.duplicate_source_ids.append(clean_src_id)
                        report.errors.append(CsvRowError(
                            row_number=idx,
                            source_record_id=clean_src_id,
                            error_category=ERROR_DUPLICATE_SOURCE_RECORD_ID,
                            error_message=f"Duplicate source_record_id '{clean_src_id}' within CSV file (row {idx})."
                        ))
                    else:
                        seen_source_ids.add(clean_src_id)

                # Row-level validation via adapter
                v_res = self.adapter.validate_source_record(row)
                if not v_res.is_valid:
                    for err in v_res.errors:
                        report.errors.append(CsvRowError(
                            row_number=idx,
                            source_record_id=clean_src_id,
                            error_category=v_res.error_category or ERROR_INVALID_SOURCE_RECORD,
                            error_message=err
                        ))
                    continue

                # Check product existence / resolution
                raw_pid = row.get("product_id") or row.get("aprs_product_id")
                src_pid = row.get("source_product_id") or row.get("sku") or row.get("asin")
                if raw_pid and src_pid and product_resolver is not None:
                    resolved_from_src = product_resolver(str(src_pid).strip())
                    if resolved_from_src and str(resolved_from_src).strip() != str(raw_pid).strip():
                        report.errors.append(CsvRowError(
                            row_number=idx,
                            source_record_id=clean_src_id,
                            error_category=ERROR_UNRESOLVED_PRODUCT,
                            error_message=(
                                f"Conflicting product identity: product_id '{raw_pid}' "
                                f"does not match resolved source_product_id '{resolved_from_src}'."
                            )
                        ))
                        continue
                try:
                    resolved_pid = resolve_product_identity(
                        raw_product_id=str(raw_pid).strip() if raw_pid else None,
                        source_product_id=str(src_pid).strip() if src_pid else None,
                        product_resolver=product_resolver,
                        db_conn=db_conn
                    )
                except ValueError as ve:
                    err_msg = str(ve)
                    cat = ERROR_UNRESOLVED_PRODUCT if ERROR_UNRESOLVED_PRODUCT in err_msg else ERROR_MISSING_PRODUCT_ID
                    report.errors.append(CsvRowError(
                        row_number=idx,
                        source_record_id=clean_src_id,
                        error_category=cat,
                        error_message=err_msg
                    ))
                    continue

                # Check conflict with existing outcome in database (if DB available)
                if db_conn is not None and clean_src_id:
                    try:
                        cur = db_conn.cursor()
                        cur.execute(
                            "SELECT outcome_id, actual_units_sold, actual_revenue, actual_landed_cogs FROM product_outcomes WHERE product_id = ? AND source_record_id = ?",
                            (resolved_pid, clean_src_id)
                        )
                        existing_row = cur.fetchone()
                        if existing_row:
                            # Normalize row in memory to compare metrics
                            norm_candidate = self.adapter.normalize(row, product_resolver=product_resolver)
                            ex_dict = dict(existing_row)
                            units_conflict = norm_candidate.actual_units_sold is not None and ex_dict["actual_units_sold"] is not None and norm_candidate.actual_units_sold != ex_dict["actual_units_sold"]
                            rev_conflict = norm_candidate.actual_revenue is not None and ex_dict["actual_revenue"] is not None and abs(norm_candidate.actual_revenue - ex_dict["actual_revenue"]) > 0.01

                            if units_conflict or rev_conflict:
                                report.conflicting_records.append({
                                    "row_number": idx,
                                    "source_record_id": clean_src_id,
                                    "product_id": resolved_pid,
                                    "existing_outcome_id": ex_dict["outcome_id"],
                                    "existing_units": ex_dict["actual_units_sold"],
                                    "incoming_units": norm_candidate.actual_units_sold,
                                })
                                report.errors.append(CsvRowError(
                                    row_number=idx,
                                    source_record_id=clean_src_id,
                                    error_category=ERROR_OUTCOME_SOURCE_CONFLICT,
                                    error_message=(
                                        f"Conflicting outcome already exists for source_record_id '{clean_src_id}' "
                                        f"(outcome_id: {ex_dict['outcome_id']}). Overwrite prohibited; "
                                        "use OutcomeIngestionService.correct_outcome to record an auditable correction."
                                    )
                                ))
                    except Exception:
                        pass
        finally:
            if close_conn and db_conn:
                db_conn.close()

        report.error_rows_count = len({e.row_number for e in report.errors if e.row_number > 0})
        report.valid_rows_count = report.total_rows - report.error_rows_count
        report.is_valid = len(report.errors) == 0
        return report

    def normalize_file(
        self,
        file_path: Union[str, Path],
        product_resolver: Optional[Callable[[str], Optional[str]]] = None,
    ) -> BatchNormalizationResult:
        """
        Parses and normalizes all rows in a local CSV file into BatchNormalizationResult.
        """
        path, _file_hash = self._verify_file_safety(file_path)
        _headers, raw_rows = self._parse_csv_file(path)
        return self.adapter.normalize_many(raw_rows, product_resolver=product_resolver)

    def ingest_file(
        self,
        file_path: Union[str, Path],
        dry_run: bool = True,
        atomic: bool = True,
        product_resolver: Optional[Callable[[str], Optional[str]]] = None,
        auto_calibrate: bool = True,
        conn=None,
    ) -> CsvIngestionReport:
        """
        Controlled ingestion workflow for local CSV files.
        
        Execution Pipeline:
          1. Validates entire file (file safety, headers, row constraints, product mapping, conflicts).
          2. If atomic=True and any validation error exists -> BLOCKS entire batch; ZERO DB writes.
          3. If dry_run=True -> Returns preview of what WOULD be ingested; ZERO DB writes.
          4. If dry_run=False -> Passes normalized payloads to Phase 3 OutcomeIngestionService.
        """
        # Step 1: Pre-validate entire file
        val_report = self.validate_file(file_path=file_path, product_resolver=product_resolver, conn=conn)

        # Step 2: Handle validation failures under atomic policy
        if atomic and not val_report.is_valid:
            status = "CONFLICT_ERROR" if val_report.conflicting_records else "BLOCKED_VALIDATION_FAILED"
            return CsvIngestionReport(
                file_path=str(file_path),
                file_hash=val_report.file_hash,
                dry_run=dry_run,
                status=status,
                total_rows=val_report.total_rows,
                ingested_count=0,
                skipped_idempotent_count=0,
                calibrations_count=0,
                errors=val_report.errors,
                row_results=[],
            )

        # Step 3: Parse and normalize rows
        path, file_hash = self._verify_file_safety(file_path)
        _headers, raw_rows = self._parse_csv_file(path)

        normalized_items: List[Tuple[int, NormalizedOutcome]] = []
        for idx, row in enumerate(raw_rows, start=1):
            try:
                norm = self.adapter.normalize(row, product_resolver=product_resolver)
                # Inject file hash into raw_reference for file-level provenance tracking
                if not norm.raw_reference:
                    norm.raw_reference = f"file_sha256:{file_hash[:16]}"
                normalized_items.append((idx, norm))
            except Exception as e:
                if atomic:
                    # In atomic mode, this shouldn't happen if validation passed, but safety guard
                    return CsvIngestionReport(
                        file_path=str(file_path),
                        file_hash=file_hash,
                        dry_run=dry_run,
                        status="BLOCKED_VALIDATION_FAILED",
                        total_rows=len(raw_rows),
                        ingested_count=0,
                        errors=[CsvRowError(row_number=idx, source_record_id=row.get("source_record_id"), error_category=ERROR_INVALID_SOURCE_RECORD, error_message=str(e))]
                    )

        # Step 4: Dry-Run Preview (ZERO database writes)
        if dry_run:
            preview_results = []
            for row_num, norm in normalized_items:
                preview_results.append({
                    "row_number": row_num,
                    "source_record_id": norm.source_record_id,
                    "product_id": norm.product_id,
                    "period_type": norm.period_type,
                    "period_start": norm.period_start,
                    "period_end": norm.period_end,
                    "actual_units_sold": norm.actual_units_sold,
                    "actual_revenue": norm.actual_revenue,
                    "action_preview": "WOULD_INGEST",
                })
            return CsvIngestionReport(
                file_path=str(path),
                file_hash=file_hash,
                dry_run=True,
                status="DRY_RUN_SUCCESS",
                total_rows=len(raw_rows),
                ingested_count=0,
                skipped_idempotent_count=0,
                calibrations_count=0,
                errors=[],
                row_results=preview_results,
            )

        # Step 5: Actual Production Ingestion via Phase 3 Ingestion Boundary
        ingested_cnt = 0
        skipped_cnt = 0
        calib_cnt = 0
        row_results = []
        exec_errors = []

        for row_num, norm in normalized_items:
            payload = norm.to_phase3_payload()
            try:
                ingest_res = OutcomeIngestionService.ingest_outcome(
                    outcome_payload=payload,
                    auto_calibrate=auto_calibrate
                )
                status_res = ingest_res.get("status")
                if status_res == "CREATED":
                    ingested_cnt += 1
                elif status_res == "IDEMPOTENT_DUPLICATE":
                    skipped_cnt += 1

                if ingest_res.get("calibration"):
                    calib_cnt += 1

                row_results.append({
                    "row_number": row_num,
                    "source_record_id": norm.source_record_id,
                    "outcome_id": ingest_res.get("outcome_id"),
                    "status": status_res,
                    "product_id": norm.product_id,
                    "decision_id": ingest_res.get("decision_id"),
                    "calibrated": ingest_res.get("calibration") is not None,
                })
            except Exception as e:
                exec_errors.append(CsvRowError(
                    row_number=row_num,
                    source_record_id=norm.source_record_id,
                    error_category=ERROR_INVALID_SOURCE_RECORD,
                    error_message=str(e)
                ))

        final_status = "INGESTED" if not exec_errors else "PARTIAL_INGESTION_WITH_ERRORS"
        return CsvIngestionReport(
            file_path=str(path),
            file_hash=file_hash,
            dry_run=False,
            status=final_status,
            total_rows=len(raw_rows),
            ingested_count=ingested_cnt,
            skipped_idempotent_count=skipped_cnt,
            calibrations_count=calib_cnt,
            errors=exec_errors,
            row_results=row_results,
        )
