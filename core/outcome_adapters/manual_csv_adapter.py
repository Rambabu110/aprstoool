# 3B. METRIC ALIAS CONFLICT DETECTION (CHECK #3)
# -------------------------------------------------------------
METRIC_ALIAS_GROUPS: Dict[str, Tuple[str, ...]] = {
    "units_sold": ("actual_units_sold", "units_sold", "units"),
    "revenue": ("actual_revenue", "revenue", "gross_sales"),
    "avg_selling_price": ("actual_avg_selling_price", "avg_selling_price", "asp", "selling_price"),
    "landed_cogs": ("actual_landed_cogs", "landed_cogs", "cogs"),
    "contribution_margin": ("actual_contribution_margin", "contribution_margin", "cm"),
    "cm_pct": ("actual_cm_pct", "cm_pct"),
    "returns_count": ("actual_returns_count", "returns_count", "returns"),
    "return_rate_pct": ("actual_return_rate_pct", "return_rate_pct"),
    "rto_count": ("actual_rto_count", "rto_count", "rto"),
    "rto_rate_pct": ("actual_rto_rate_pct", "rto_rate_pct"),
    "ad_spend": ("actual_ad_spend", "ad_spend", "marketing_spend"),
    "cac": ("actual_cac", "cac"),
    "inventory": ("actual_inventory", "inventory"),
    "stockout_days": ("actual_stockout_days", "stockout_days"),
    "product_id": ("product_id", "aprs_product_id"),
    "source_product_id": ("source_product_id", "sku", "asin"),
}

def check_metric_alias_conflicts(record: Dict[str, Any]) -> List[str]:
    """
    Checks if multiple aliases for the same metric are supplied with conflicting values.
    If multiple aliases are present with identical values, they are accepted deterministically.
    If multiple aliases are present with different values, returns explicit conflict error messages.
    """
    errors = []
    for canonical_name, aliases in METRIC_ALIAS_GROUPS.items():
        present_values = {}
        for alias in aliases:
            if alias in record and record[alias] is not None:
                val_str = str(record[alias]).strip()
                if val_str != "":
                    present_values[alias] = val_str

        if len(present_values) > 1:
            first_alias, first_val = next(iter(present_values.items()))
            for other_alias, other_val in present_values.items():
                if other_alias == first_alias:
                    continue
                is_different = False
                try:
                    f1 = float(first_val)
                    f2 = float(other_val)
                    if not math.isclose(f1, f2, abs_tol=1e-5):
                        is_different = True
                except (ValueError, TypeError):
                    if first_val != other_val:
                        is_different = True

                if is_different:
                    errors.append(
                        f"{ERROR_INVALID_NUMERIC_VALUE}: Conflicting values provided for aliased column '{canonical_name}': "
                        f"'{first_alias}'='{first_val}' vs '{other_alias}'='{other_val}'. Multiple aliases must not differ."
                    )
                    break
    return errors


